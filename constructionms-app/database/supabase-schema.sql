CREATE OR REPLACE FUNCTION constructionms_guard_material_catalog_request_mutation()
RETURNS trigger AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'Material catalog requests cannot be deleted.';
    END IF;

