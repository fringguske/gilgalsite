-- 1. Row Level Security on every application table, with no policies. The
--    backend connects as the table owner (role "postgres"), which bypasses RLS;
--    every other role is denied by default.
DO $rls$
DECLARE
    table_record record;
BEGIN
    FOR table_record IN
        SELECT tablename FROM pg_tables WHERE schemaname = 'public'
    LOOP
        EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', table_record.tablename);
    END LOOP;
END
$rls$;

-- 2. Remove the Data API roles' direct privileges on the application objects.
DO $revoke$
DECLARE
    api_role text;
BEGIN
    FOREACH api_role IN ARRAY ARRAY['anon', 'authenticated']
    LOOP
        IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = api_role) THEN
            EXECUTE format('REVOKE ALL ON ALL TABLES IN SCHEMA public FROM %I', api_role);
            EXECUTE format('REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM %I', api_role);
            EXECUTE format('REVOKE ALL ON ALL FUNCTIONS IN SCHEMA public FROM %I', api_role);
        END IF;
    END LOOP;
END
$revoke$;

-- 3. Private bucket for evidence files. Files are only ever read and written by
--    the backend with the service-role key and streamed through the API.
DO $bucket$
BEGIN
    IF to_regclass('storage.buckets') IS NOT NULL THEN
        INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
        VALUES (
            'evidence',
            'evidence',
            false,
            4194304,
            ARRAY['application/pdf', 'image/jpeg', 'image/png', 'image/webp'])
        ON CONFLICT (id) DO NOTHING;
    END IF;
END
$bucket$;

