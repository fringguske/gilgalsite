-- =============================================================================
-- ConstructionMS - complete database schema for Supabase (PostgreSQL 15+)
-- =============================================================================
-- Run this ONCE against a fresh Supabase project:
--   Supabase Dashboard -> SQL Editor -> New query -> paste this file -> Run
--   (or: psql "$DATABASE_URL" -v ON_ERROR_STOP=1 -f supabase-schema.sql)
--
-- What it creates (all inside the "public" schema, same names as before):
--   * every table, identity column, foreign key, check constraint and filtered
--     unique index from the original 29 EF Core migrations, applied in order;
--   * the append-only / source-immutability / cross-record validation trigger
--     functions and triggers that independently protect workflow evidence;
--   * the seed data the migrations inserted (roles, the four Gilgal projects,
--     their cost codes and the starter material catalog);
--   * Supabase hardening: Row Level Security is enabled on every table with NO
--     policies and the anon/authenticated API roles are revoked, so the public
--     Supabase Data API (PostgREST) cannot read or write any business record.
--     The Next.js backend connects with the database owner connection string,
--     which is not subject to RLS;
--   * the private "evidence" Storage bucket used for uploaded PDF/JPEG/PNG/WebP
--     evidence files (4 MB limit, matching the Vercel request-body budget).
--
-- The whole script runs in one transaction: any error leaves the database
-- untouched. After it succeeds, create the first Administrator with
--   npm run bootstrap-administrator   (constructionms-app/scripts/bootstrap-administrator.ts)
-- =============================================================================

