-- =============================================================================
-- UPGRADE: emailed verification codes (Resend).
--
-- Run this once in the Supabase SQL Editor on a database that was created from
-- an earlier copy of supabase-schema.sql (before it contained the "Emailed
-- verification codes" section). New databases already have these objects.
-- It is safe to run more than once, and also works on a database that ran the
-- earlier upgrade-phone-verification.sql, when the codes were sent by SMS.
--
-- Adds:
--   * "Users"."EmailVerifiedAt"           - set once a code sent to the address is used;
--   * "EmailVerificationCodes"            - hashed one-time codes, 10-minute lifetime;
--   * the 'EmailVerified' and 'PasswordReset' security audit event types.
-- Removes, where the SMS version added them (nothing else uses them):
--   * "PhoneVerificationCodes", "Users"."PhoneNumberVerifiedAt" and
--     "AccessRequests"."PhoneNumber".
-- =============================================================================

BEGIN;

SET LOCAL search_path TO public;

ALTER TABLE "Users" ADD COLUMN IF NOT EXISTS "EmailVerifiedAt" timestamp with time zone;

CREATE TABLE IF NOT EXISTS "EmailVerificationCodes" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY,
    "UserId" integer NOT NULL,
    "Purpose" character varying(30) NOT NULL,
    "Email" character varying(254) NOT NULL,
    "CodeHash" character varying(64) NOT NULL,
    "CreatedAt" timestamp with time zone NOT NULL,
    "ExpiresAt" timestamp with time zone NOT NULL,
    "FailedAttempts" integer NOT NULL DEFAULT 0,
    "ConsumedAt" timestamp with time zone,
    CONSTRAINT "PK_EmailVerificationCodes" PRIMARY KEY ("Id"),
    CONSTRAINT "CK_EmailVerificationCodes_Purpose" CHECK ("Purpose" IN ('ChangePassword', 'VerifyEmail', 'ResetPassword')),
    CONSTRAINT "CK_EmailVerificationCodes_Email" CHECK ("Email" LIKE '_%@_%'),
    CONSTRAINT "CK_EmailVerificationCodes_Expiry" CHECK ("ExpiresAt" > "CreatedAt"),
    CONSTRAINT "CK_EmailVerificationCodes_FailedAttempts" CHECK ("FailedAttempts" >= 0),
    CONSTRAINT "FK_EmailVerificationCodes_Users_UserId" FOREIGN KEY ("UserId") REFERENCES "Users" ("Id") ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS "IX_EmailVerificationCodes_UserId_CreatedAt" ON "EmailVerificationCodes" ("UserId", "CreatedAt");

DROP TABLE IF EXISTS "PhoneVerificationCodes";

ALTER TABLE "Users" DROP COLUMN IF EXISTS "PhoneNumberVerifiedAt";

ALTER TABLE "AccessRequests" DROP COLUMN IF EXISTS "PhoneNumber";

-- 'PhoneNumberVerified' stays allowed so events recorded while codes went by SMS remain valid.
ALTER TABLE "SecurityAuditEvents" DROP CONSTRAINT IF EXISTS "CK_SecurityAuditEvents_EventType";

ALTER TABLE "SecurityAuditEvents" ADD CONSTRAINT "CK_SecurityAuditEvents_EventType" CHECK ("EventType" IN ('UsernameChanged', 'PasswordChanged', 'AdministratorPasswordReset', 'UserCreated', 'UserProfileUpdated', 'UserRoleChanged', 'UserActivated', 'UserDeactivated', 'EmailVerified', 'PasswordReset', 'PhoneNumberVerified'));

-- Same Supabase hardening as every other table: RLS on with no policies, and no
-- direct access for the Data API roles.
ALTER TABLE "EmailVerificationCodes" ENABLE ROW LEVEL SECURITY;

DO $revoke$
DECLARE
    api_role text;
BEGIN
    FOREACH api_role IN ARRAY ARRAY['anon', 'authenticated']
    LOOP
        IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = api_role) THEN
            EXECUTE format('REVOKE ALL ON TABLE "EmailVerificationCodes" FROM %I', api_role);
            EXECUTE format('REVOKE ALL ON SEQUENCE "EmailVerificationCodes_Id_seq" FROM %I', api_role);
        END IF;
    END LOOP;
END
$revoke$;

COMMIT;
